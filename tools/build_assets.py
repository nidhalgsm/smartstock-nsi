"""Embeds design/ images into frontend/assets.js as data URIs, so the site needs no separate image files.
Run after changing an image in design/:   python tools/build_assets.py        (add --check to only verify)"""
import base64, os, re, sys
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FILES = {"favicon": ("favicon.svg", "image/svg+xml"), "icon192": ("icon-192.png", "image/png"), "icon512": ("icon-512.png", "image/png"), "bg": ("bg.jpg", "image/jpeg")}
raw = lambda n: open(os.path.join(root, "design", n), "rb").read()
out = os.path.join(root, "frontend", "assets.js")
if "--check" in sys.argv:
    js = open(out, encoding="utf-8").read(); bad = []
    for k, (n, mime) in FILES.items():
        m = re.search(rf'{k}: "data:{re.escape(mime)};base64,([A-Za-z0-9+/=]+)"', js)
        if not m or base64.b64decode(m.group(1)) != raw(n): bad.append(k)
    print("ASSETS OK (decoded bytes identical to design/ files)" if not bad else f"ASSETS MISMATCH: {bad}"); sys.exit(1 if bad else 0)
uri = lambda n, m: f"data:{m};base64," + base64.b64encode(raw(n)).decode()
body = ",\n".join(f'  {k}: "{uri(n, m)}"' for k, (n, m) in FILES.items())
js = f'''// AUTO-GENERATED by tools/build_assets.py from the files in design/ - do not edit by hand.
// Holds the logo, app icons and background image as code, and applies them (loaded in <head> before app.js).
const ASSETS = {{
{body}
}};
(function () {{
  const d = document, add = (rel, href, type) => {{ const l = d.createElement("link"); l.rel = rel; l.href = href; if (type) l.type = type; d.head.appendChild(l); }};
  d.documentElement.style.setProperty("--bg-img", 'url("' + ASSETS.bg + '")');            // blurred background (used by styles.css)
  add("icon", ASSETS.favicon, "image/svg+xml"); add("apple-touch-icon", ASSETS.icon192);   // favicon + iPhone home-screen icon
  const manifest = {{ name: "SmartStock TN", short_name: "SmartStock", start_url: location.origin + "/", scope: location.origin + "/", display: "standalone",
    background_color: "#141414", theme_color: "#d96900",
    icons: [{{ src: ASSETS.icon192, sizes: "192x192", type: "image/png" }}, {{ src: ASSETS.icon512, sizes: "512x512", type: "image/png", purpose: "any maskable" }}] }};
  add("manifest", "data:application/manifest+json;charset=utf-8," + encodeURIComponent(JSON.stringify(manifest)));   // "install app" on phones
}})();
'''
open(out, "w", encoding="utf-8").write(js); print("wrote", out, round(len(js) / 1024), "KB")
